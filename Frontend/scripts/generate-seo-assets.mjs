#!/usr/bin/env node
/**
 * Generates public/robots.txt and public/sitemap.xml from the route table in
 * src/config/seoConfig.js, so they can never drift from what the app actually
 * serves. Runs before every build (see package.json "prebuild").
 *
 * Both files were previously hand-maintained and pointed at
 * https://siteaudit.sltechsoft.com, a host that no longer resolves.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

// The config uses import.meta.env, which only exists under Vite. Read the values
// out of the source directly rather than importing it into plain Node.
const configSrc = fs.readFileSync(path.join(root, 'src/config/seoConfig.js'), 'utf8');

const SITE_ORIGIN = (
  process.env.VITE_SITE_ORIGIN
  || configSrc.match(/\|\|\s*'(https?:\/\/[^']+)'/)?.[1]
  || 'https://dealersiteaudit.com'
).replace(/\/+$/, '');

/** Parse the route table without evaluating the module. */
const parseRoutes = () => {
  const body = configSrc.slice(
    configSrc.indexOf('export const SEO_CONFIGS'),
    configSrc.indexOf('export const DEFAULT_SEO'),
  );
  const blocks = body.split(/\n\s*\{\s*\n/).slice(1);
  return blocks.map((block) => ({
    path: block.match(/path:\s*'([^']+)'/)?.[1],
    noindex: /noindex:\s*true/.test(block),
    prefix: /prefix:\s*true/.test(block),
    priority: parseFloat(block.match(/priority:\s*([\d.]+)/)?.[1] ?? '0.5'),
    changefreq: block.match(/changefreq:\s*'([^']+)'/)?.[1] || 'monthly',
  })).filter((r) => r.path);
};

const routes = parseRoutes();
const indexable = routes.filter((r) => !r.noindex);
const excluded = routes.filter((r) => r.noindex);
const today = new Date().toISOString().slice(0, 10);

// ── sitemap.xml — only canonical, indexable URLs ──
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((r) => `  <url>
    <loc>${SITE_ORIGIN}${r.path === '/' ? '/' : r.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${r.changefreq}</changefreq>
    <priority>${r.priority.toFixed(1)}</priority>
  </url>`).join('\n')}
</urlset>
`;

// ── robots.txt — every noindex route is disallowed, derived from the same flag ──
const robots = `# Generated by scripts/generate-seo-assets.mjs — do not edit by hand.
User-agent: *
Allow: /

# Authenticated and transactional surfaces. These carry noindex in the route table,
# so this list is generated from it and cannot fall out of step.
${excluded.map((r) => `Disallow: ${r.path}`).join('\n')}

# Query-string variants produce duplicate content.
Disallow: /*?*tab=
Disallow: /*?*sort=
Disallow: /*?*filter=

Sitemap: ${SITE_ORIGIN}/sitemap.xml
`;

fs.writeFileSync(path.join(root, 'public/sitemap.xml'), sitemap);
fs.writeFileSync(path.join(root, 'public/robots.txt'), robots);

console.log(`[seo] origin      ${SITE_ORIGIN}`);
console.log(`[seo] sitemap.xml ${indexable.length} indexable URLs`);
console.log(`[seo] robots.txt  ${excluded.length} disallowed paths`);
